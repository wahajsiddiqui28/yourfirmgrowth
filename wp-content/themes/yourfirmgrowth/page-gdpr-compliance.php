<div class="yfg-legal">

	<h2>1. Our Commitment to GDPR</h2>
	<p>At Your Firm Growth (&ldquo;YFG&rdquo;), protecting personal data is central to how we operate. As a full-service digital agency working with clients across the United Kingdom, Germany, the wider European market, and worldwide, we are committed to complying with the General Data Protection Regulation (GDPR) and the UK GDPR in everything we do. This statement explains how we meet those obligations for our own data processing and for the work we deliver on behalf of our clients.</p>

	<h2>2. What Is the GDPR?</h2>
	<p>The General Data Protection Regulation is a European data-protection law that governs how organisations collect, use, store, and protect the personal data of individuals in the EU and, through the UK GDPR, in the United Kingdom. It gives individuals stronger rights over their data and requires organisations to handle that data lawfully, transparently, and securely.</p>

	<h2>3. Our Role: Controller and Processor</h2>
	<p>Depending on the activity, YFG acts in one of two roles:</p>
	<ul>
		<li>As a <strong>data controller</strong> for the personal data we collect through our own website, marketing, and business operations, we decide how and why that data is processed.</li>
		<li>As a <strong>data processor</strong> when we deliver services such as marketing, SEO, or web development, we process personal data on our clients&rsquo; documented instructions, and the client remains the data controller.</li>
	</ul>

	<h2>4. The Data Protection Principles We Follow</h2>
	<p>We handle all personal data in line with the GDPR&rsquo;s core principles:</p>
	<ul>
		<li><strong>Lawfulness, fairness, and transparency</strong> — we process data lawfully and tell people how their data is used.</li>
		<li><strong>Purpose limitation</strong> — we collect data only for specified, legitimate purposes.</li>
		<li><strong>Data minimisation</strong> — we collect only what we genuinely need.</li>
		<li><strong>Accuracy</strong> — we keep data accurate and up to date.</li>
		<li><strong>Storage limitation</strong> — we keep data only as long as necessary.</li>
		<li><strong>Integrity and confidentiality</strong> — we protect data with appropriate security.</li>
		<li><strong>Accountability</strong> — we take responsibility for compliance and can demonstrate it.</li>
	</ul>

	<h2>5. Lawful Bases for Processing</h2>
	<p>We only process personal data where we have a valid lawful basis under the GDPR, namely consent, the performance of a contract, compliance with a legal obligation, or our legitimate interests where these are not overridden by an individual&rsquo;s rights. Where we rely on consent, individuals can withdraw it at any time.</p>

	<h2>6. Your Rights and How We Uphold Them</h2>
	<p>We respect and facilitate the rights the GDPR gives to individuals, including the rights of access, rectification, erasure, restriction, data portability, and objection, as well as the right to withdraw consent and to lodge a complaint with a supervisory authority. We have processes in place to respond to such requests within the statutory time limits.</p>

	<h2>7. Data Security Measures</h2>
	<p>We apply appropriate technical and organisational measures to keep personal data secure, including:</p>
	<ul>
		<li>Encryption of data in transit and, where appropriate, at rest.</li>
		<li>Role-based access controls and strong authentication.</li>
		<li>Secure, reputable hosting and infrastructure providers.</li>
		<li>Regular software updates, monitoring, and backups.</li>
		<li>Confidentiality obligations and data-protection awareness across our team.</li>
	</ul>

	<h2>8. Working With Sub-Processors</h2>
	<p>Where we use third-party sub-processors (for example, hosting, analytics, email, or advertising platforms) to help deliver our services, we carry out due diligence on their data-protection standards and put appropriate contracts in place that require them to protect personal data and process it only on documented instructions. A current list of sub-processors is available on request.</p>

	<h2>9. International Data Transfers</h2>
	<p>Where personal data is transferred outside the UK or European Economic Area, we ensure appropriate safeguards are in place, such as an adequacy decision or the UK/EU Standard Contractual Clauses, so that the data continues to receive an equivalent level of protection.</p>

	<h2>10. Data Breach Notification</h2>
	<p>We have procedures to detect, report, and investigate personal data breaches. Where a breach is likely to result in a risk to individuals&rsquo; rights and freedoms, we will notify the relevant supervisory authority without undue delay and, where required, within 72 hours of becoming aware of it, and we will inform affected individuals where the law requires.</p>

	<h2>11. Staff Awareness and Accountability</h2>
	<p>Everyone at YFG who handles personal data is made aware of their data-protection responsibilities and our internal policies. We keep records of our processing activities and review our practices regularly to maintain and demonstrate compliance.</p>

	<h2>12. Our Clients' Responsibilities</h2>
	<p>When we act as a processor on behalf of a client, the client, as data controller, is responsible for ensuring they have a lawful basis to collect and share the personal data they provide to us and for informing their own data subjects appropriately. Our respective responsibilities are set out in our services agreement and data processing terms.</p>

